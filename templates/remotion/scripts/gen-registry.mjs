// Scans src/shots/**/*.tsx (never src/lib, never src/shots/brand.json — only .tsx files
// under src/shots), extracts each file's compositionConfig, and writes:
//   src/registry.gen.tsx     — imports every shot for Root.tsx
//   src/shots.manifest.json  — metadata for the bulk renderer
// Run before `remotion studio` / render (npm run gen does this).
import {
  readdirSync, readFileSync, writeFileSync, statSync,
} from 'fs';
import { fileURLToPath, pathToFileURL } from 'url';
import path from 'path';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const shotsDir = path.join(root, 'src', 'shots');

function walk(dir) {
  const out = [];
  for (const name of readdirSync(dir)) {
    const p = path.join(dir, name);
    if (statSync(p).isDirectory()) out.push(...walk(p));
    else if (name.endsWith('.tsx')) out.push(p);
  }
  return out;
}

// Reads id (required), durationInFrames (preferred) or durationInSeconds*fps, fps
// (default 30), width (default 1920), height (default 1080), transparent (default
// false) out of a shot file's `export const compositionConfig = { ... };` block.
// Trailing `// comment`s after a value are harmless: every field regex only captures
// the value's own characters (digits, or a quoted string), never anything past it.
export function parseConfig(src) {
  const block = /export\s+const\s+compositionConfig\s*=\s*{([\s\S]*?)}\s*;/.exec(src);
  if (!block) return null;
  const body = block[1];
  const str = (k) => {
    const m = new RegExp(`${k}\\s*:\\s*['"]([^'"]+)['"]`).exec(body);
    return m ? m[1] : undefined;
  };
  const num = (k) => {
    const m = new RegExp(`${k}\\s*:\\s*([0-9.]+)`).exec(body);
    return m ? Number(m[1]) : undefined;
  };
  const bool = (k) => new RegExp(`${k}\\s*:\\s*true`).test(body);
  const id = str('id');
  if (!id) return null;
  const fps = num('fps') ?? 30;
  const width = num('width') ?? 1920;
  const height = num('height') ?? 1080;
  const transparent = bool('transparent');
  const durationInFrames = num('durationInFrames') ?? Math.round((num('durationInSeconds') ?? 5) * fps);
  return {
    id, durationInFrames, fps, width, height, transparent,
  };
}

function generate() {
  let files = [];
  try {
    files = walk(shotsDir);
  } catch {
    files = [];
  }

  const shots = [];
  const seen = new Set();
  for (const file of files.sort()) {
    const cfg = parseConfig(readFileSync(file, 'utf8'));
    if (!cfg) {
      console.warn('  skip (no compositionConfig):', path.relative(root, file));
      continue;
    }
    if (seen.has(cfg.id)) {
      console.warn('  DUPLICATE id, skipping:', cfg.id, path.relative(root, file));
      continue;
    }
    seen.add(cfg.id);
    const imp = `./${path.relative(path.join(root, 'src'), file).replace(/\\/g, '/').replace(/\.tsx$/, '')}`;
    shots.push({ ...cfg, imp });
  }

  const header = '// AUTO-GENERATED by scripts/gen-registry.mjs — do not edit.\n';
  let reg = `${header}import type React from 'react';\n`;
  shots.forEach((s, i) => { reg += `import Shot${i}, { compositionConfig as cfg${i} } from '${s.imp}';\n`; });
  reg += '\nexport const shots: { Comp: React.FC; config: any }[] = [\n';
  shots.forEach((s, i) => { reg += `  { Comp: Shot${i} as React.FC, config: cfg${i} },\n`; });
  reg += '];\n';
  writeFileSync(path.join(root, 'src', 'registry.gen.tsx'), reg);

  writeFileSync(
    path.join(root, 'src', 'shots.manifest.json'),
    JSON.stringify(shots.map(({ imp, ...m }) => m), null, 1),
  );

  console.log(`gen-registry: ${shots.length} shot(s) -> registry.gen.tsx`);
  shots.forEach((s) => console.log(`  - ${s.id}  ${s.width}x${s.height}@${s.fps}fps ${s.durationInFrames}f${s.transparent ? ' [alpha]' : ''}`));
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  generate();
}
